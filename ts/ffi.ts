export function text(
  data: Uint8Array,
  offset = 0,
  length = data.length - offset,
) {
  const slice = data.subarray(offset, offset + length)
  const end = slice.indexOf(0)
  return new TextDecoder().decode(end < 0 ? slice : slice.subarray(0, end))
}
